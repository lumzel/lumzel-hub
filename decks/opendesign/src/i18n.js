let currentLocale = 'en';

export function setLocale(loc) {
  currentLocale = loc && String(loc).toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
  document.documentElement.lang = currentLocale === 'zh-CN' ? 'zh-CN' : 'en';
  return currentLocale;
}

export function getLocale() {
  return currentLocale;
}

export function t(key, vars) {
  const dict = STRINGS[currentLocale] || STRINGS.en;
  let text = dict[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
}
