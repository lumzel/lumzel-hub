let currentLocale = 'zh-CN';

export function setLocale(raw) {
  currentLocale = String(raw || '').toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = currentLocale;
  }
  return currentLocale;
}

export function getLocale() {
  return currentLocale;
}

export function t(key, vars) {
  const dict = DICT[currentLocale] || DICT.en;
  let str = dict[key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, v === undefined || v === null ? '' : String(v));
    }
  }
  return str;
}

export function applyI18n(root = typeof document !== 'undefined' ? document : null) {
  if (!root) return;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.getAttribute('data-i18n'));
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  }
}
